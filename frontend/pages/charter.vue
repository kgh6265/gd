            </ul>
          </div>

          <div>
            <h4 class="text-lg font-bold">8.2 Membership Standing</h4>
            <p>Membership in the Graphic Design Club is contingent upon continued participation, responsible conduct, and adherence to the provisions of this Charter.</p>
            <p class="mt-2">Club Associates who become unresponsive to official club communications and fail to participate in assigned responsibilities for a period exceeding fourteen (14) consecutive days without prior notice may be subject to a Membership Review.</p>
