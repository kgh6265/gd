            <p class="mt-2">If the membership votes to retain the current administration through the annual Club Governance Vote, the existing administration may continue serving for the following academic year.</p>
            <p class="mt-2">If the membership votes to conduct leadership elections, the terms of the existing administration shall conclude upon the formal assumption of office by the newly appointed administration, which shall ordinarily occur at the conclusion of the Spring semester.</p>
