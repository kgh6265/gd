          <div>
            <h4 class="text-lg font-bold">7.2 Club Governance Vote</h4>
            <p>The Graphic Design Club shall conduct an annual Club Governance Vote during the seventh week of the Spring semester.</p>
            <p class="mt-2">The Club Governance Vote serves as the primary mechanism through which Club Associates determine the leadership direction of the organization for the upcoming academic year.</p>
            <p class="mt-2">The Governance Vote shall be conducted among all Club Associates. No member of the administration, including the President, may be excluded from participation, nor may any eligible Club Associate be denied the right to vote.</p>
            <p class="mt-2">The Governance Vote shall be centered on a single fundamental question:</p>
            <ul class="list-disc ml-6 mt-2">
              <li>Whether the current administration shall continue into the following academic year or whether presidential elections shall be conducted.</li>
            </ul>
            <p class="mt-2">The Governance Vote shall be conducted through a fair, transparent, and accessible voting process. Results shall be documented, archived, and made available to Club Associates following the conclusion of voting.</p>
            <p class="mt-2">The option receiving a simple majority of valid votes cast shall constitute the official decision of the membership. The outcomes of the Governance Vote shall be binding upon the administration and shall serve as the official determination of the club's leadership direction for the following academic year.</p>
            <p class="mt-2">No member of the administration, including the President, may suspend, cancel, alter, delay, manipulate, override, or disregard the results of a duly conducted Governance Vote.</p>
          </div>

          <div>
            <h4 class="text-lg font-bold">7.3 Presidential Elections</h4>
            <p>If the Club Governance Vote indicates that leadership elections shall be conducted, a presidential election shall be held.</p>
            <p class="mt-2">Only current Department Directors shall be eligible to stand for election as President. All Club Associates shall be eligible to vote in presidential elections. The candidate receiving the highest number of valid votes shall be elected President for the upcoming academic year.</p>
            <p class="mt-2">If no eligible Department Director chooses to stand for election, the Executive Department in office at that time may identify and approve qualified Club Associates to participate in the election.</p>
          </div>

          <div>
            <h4 class="text-lg font-bold">7.4 Executive Appointments</h4>
            <p>Following the conclusion of a presidential election, or following a decision by the membership to retain the current administration through the Club Governance Vote, the President shall possess sole authority to appoint Department Directors and the Treasurer.</p>
            <p class="mt-2">Such appointments shall be made at the President's discretion from among the club's Club Associates. No election, vote, approval, or ratification shall be required for these appointments.</p>
            <p class="mt-2">The President may reorganize, create, merge, dissolve, or fill leadership positions as necessary to support the club's mission, objectives, and operational needs. Any such changes shall be formally documented and communicated to the club's leadership and membership.</p>
          </div>

          <div>
            <h4 class="text-lg font-bold">7.5 Vacancies and Resignations</h4>
            <p>Any leadership member may resign from their position by submitting written notice to the President.</p>
            <p class="mt-2">In the event that a Department Director, Treasurer, or any other appointed position becomes vacant through resignation, removal, or inability to fulfill its responsibilities, the President shall appoint a replacement from among the club's Club Associates. Such appointments shall take effect immediately unless otherwise specified by the President.</p>
            <p class="mt-2">In the event that the office of President becomes vacant, the sitting Department Directors shall, by majority vote, appoint one of the current Department Directors to assume the office of President.</p>
            <p class="mt-2">If the sitting Department Directors are unable to reach a majority decision, the Faculty Advisor shall facilitate further deliberation. If a majority decision remains unattainable, the Faculty Advisor shall appoint one of the sitting Department Directors to assume the office of President.</p>
            <p class="mt-2">If no sitting Department Directors are available or willing to assume the office of President, the Faculty Advisor shall appoint an interim President from among the club's Club Associates. The interim President shall possess the authority necessary to administer the club and appoint a new Executive Department in accordance with this Charter.</p>
            <p class="mt-2">Any President appointed through the procedures outlined in this section shall possess the same authority, responsibilities, and powers as a President elected or retained through the Club Governance Vote.</p>
          </div>

