            <p class="mt-2">To ensure a safe, productive, and reliable environment, all GD Friends must adhere to a baseline standard of conduct. The Executive Department reserves the right to evaluate their participation and may revoke a GD Friend's status at any time. Grounds for revoking status include, but are not limited to:</p>
            <ul class="list-disc ml-6 mt-2 space-y-1">
              <li>Failing to fulfill voluntary commitments or complete accepted tasks without proper notice.</li>
              <li>Engaging in disruptive, disrespectful, or unprofessional behavior during club events or on official communication channels.</li>
