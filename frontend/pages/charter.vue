            <h4 class="text-lg font-bold">8.3 Communication and Participation Requirements</h4>
            <p>Official club communication, collaboration, and recordkeeping platforms may include, but are not limited to, messaging groups, project management systems, cloud storage platforms, financial tracking systems, and other digital resources designated by club leadership.</p>
            <p class="mt-2">Access to official club communication channels, records, resources, and platforms shall be restricted to Club Associates only.</p>
            <p class="mt-2">Club Associates are required to remain in the club's official communication channels and regularly check them for updates, announcements, and responsibilities. Presence in these channels is a condition of membership.</p>
            <p class="mt-2">Club-related matters, including ideas, proposals, project discussions, planning activities, operational decisions, and department-related initiatives, must be communicated through the appropriate official club channels whenever reasonably possible.</p>
            <p class="mt-2">Members shall not rely upon private communications as the primary means of conducting club business, proposing initiatives, making decisions, assigning responsibilities, or discussing matters affecting the club's operations. Discussions relating to club activities should occur within the appropriate departmental or organizational channels to promote transparency, collaboration, accountability, and organizational continuity.</p>
            <p class="mt-2">This requirement shall apply equally to Club Associates, including Department Directors, the Treasurer, and the President.</p>
            <p class="mt-2">Nothing in this section shall prohibit private communications relating to personal matters, complaints, conflict resolution, sensitive issues, disciplinary matters, wellbeing concerns, or other situations where confidentiality may be appropriate.</p>
            <p class="mt-2">Club Associates are expected to respond to communications relating to their responsibilities within a reasonable timeframe and to remain informed of matters affecting their department, projects, or assigned duties.</p>
            <p class="mt-2">Persistent failure to acknowledge, respond to, or act upon communications in a timely manner, particularly where such delays negatively affect club operations, projects, events, or decision-making processes, may be considered a failure to fulfill assigned responsibilities and may be addressed through the accountability procedures outlined in this Charter.</p>
          </div>

          <div>
            <h4 class="text-lg font-bold">8.4 Authority for Accountability Actions</h4>
            <p>The President shall serve as the sole authority responsible for the issuance of Reminders, Concern Notices, Membership Reviews, and membership removals under this Charter.</p>
            <p class="mt-2">Department Directors may identify concerns, document issues, and submit recommendations to the President regarding the conduct, participation, or performance of Club Associates within their respective departments. However, Department Directors shall not possess the authority to issue Reminders, Concern Notices, Membership Reviews, or membership removals independently.</p>
            <p class="mt-2">The President may consult with Department Directors, the Treasurer, the Faculty Advisor, or other relevant individuals when evaluating a matter. However, all accountability actions shall remain the responsibility of the President unless otherwise specified by this Charter.</p>
            <p class="mt-2">The President shall communicate all Reminders, Concern Notices, Membership Reviews, and membership removals directly to the affected individual. Concern Notices, Membership Reviews, and membership removals shall be formally documented and maintained within the club's accountability records.</p>
          </div>

          <div>
            <h4 class="text-lg font-bold">8.5 Reminders</h4>
            <p>A Reminder is an informal notice issued by the President when a minor concern is identified.</p>
            <p class="mt-2">Examples may include:</p>
            <ul class="list-disc ml-6 mt-2 space-y-1">
              <li>Missing a required meeting.</li>
              <li>Missing a project deadline.</li>
              <li>Failing to respond to communications.</li>
              <li>Neglecting assigned responsibilities.</li>
              <li>Minor violations of club expectations.</li>
            </ul>
            <p class="mt-2">The purpose of a Reminder is to encourage improvement, provide guidance, and clarify expectations rather than impose disciplinary action. Reminders shall not be considered disciplinary records.</p>
            <p class="mt-2">A member may receive up to three (3) Reminders for similar or repeated concerns. Upon the issuance of a third Reminder, the matter shall escalate to the Concern Notice stage.</p>
          </div>

          <div>
            <h4 class="text-lg font-bold">8.6 Concern Notices</h4>
            <p>Concern Notices are formal notices issued by the President after a member has accumulated three (3) Reminders or when a concern persists beyond the Reminder stage.</p>
            <p class="mt-2">A Concern Notice shall:</p>
            <ul class="list-disc ml-6 mt-2 space-y-1">
              <li>Clearly identify the concern.</li>
              <li>Explain the expected corrective actions.</li>
              <li>Inform the member of the consequences of continued violations.</li>
            </ul>
            <p class="mt-2">Concern Notices shall be documented and communicated directly to the affected individual. Once a member enters the Concern Notice stage, subsequent issues shall be addressed through additional Concern Notices rather than Reminders. Concern Notices shall remain active for one academic semester from the date of issuance. Members shall have the right to request information regarding any active Concern Notices issued against them.</p>
          </div>

          <div>
            <h4 class="text-lg font-bold">8.7 Membership Review</h4>
            <p>A Membership Review may be initiated when:</p>
            <ul class="list-disc ml-6 mt-2 space-y-1">
              <li>A member accumulates three (3) active Concern Notices.</li>
              <li>A member becomes unresponsive for more than fourteen (14) consecutive days without prior notice.</li>
              <li>A member repeatedly fails to fulfill assigned responsibilities.</li>
              <li>A member consistently fails to complete assigned duties in a timely, accurate, or effective manner, or fails to meet clearly communicated expectations for their role, despite receiving reminders, guidance, or corrective action.</li>
              <li>A member's conduct negatively affects the club, its members, or its operations.</li>
            </ul>
            <p class="mt-2">During a Membership Review, the member shall be informed of the concerns and provided an opportunity to respond.</p>
            <p class="mt-2">Following review, the President may determine whether the member's membership should be terminated. The basis for such determination shall be documented within the club's accountability records.</p>
          </div>

          <div>
            <h4 class="text-lg font-bold">8.8 Major Misconduct</h4>
            <p>Certain actions may warrant immediate Membership Review without the issuance of Reminders or Concern Notices.</p>
            <p class="mt-2">Examples include:</p>
            <ul class="list-disc ml-6 mt-2 space-y-1">
              <li>Harassment or discrimination.</li>
              <li>Deliberate damage to club property or resources.</li>
              <li>Misuse of club funds or assets.</li>
              <li>Serious violations of university policies.</li>
              <li>Conduct that significantly harms the reputation, operations, or welfare of the club.</li>
            </ul>
            <p class="mt-2">Such matters may result in immediate removal from leadership positions, termination of membership, or other corrective actions deemed appropriate by the President.</p>
          </div>

          <div>
            <h4 class="text-lg font-bold">8.9 Removal from Leadership</h4>
            <p>Department Directors, the Treasurer, and any other appointed leadership positions shall be subject to the same accountability procedures as all other Club Associates.</p>
            <p class="mt-2">Following a Membership Review, the President may remove a Department Director, the Treasurer, or any other appointed leader from office if continued service is determined to be contrary to the interests, operations, or objectives of the club. Any such removal shall be documented and communicated to the affected individual.</p>
            <p class="mt-2">Removal from a leadership position shall not automatically terminate the individual's club membership unless separately determined through the Membership Review process.</p>
          </div>

          <div>
            <h4 class="text-lg font-bold">8.10 Presidential Accountability</h4>
            <p>A Presidential Review may be initiated if the President:</p>
            <ul class="list-disc ml-6 mt-2 space-y-1">
              <li>Repeatedly fails to perform the duties of the office.</li>
              <li>Consistently fails to fulfill the responsibilities of the office to an acceptable standard.</li>
              <li>Violates the provisions of this Charter.</li>
              <li>Engages in misconduct that materially harms the club, its members, or its reputation.</li>
              <li>Misuses the authority granted to the office of President.</li>
              <li>Becomes subject to repeated accountability actions under the club's accountability procedures.</li>
            </ul>
            <p class="mt-2">A Presidential Review may be requested through a written submission to the Faculty Advisor supported by a simple majority of sitting Department Directors.</p>
            <p class="mt-2">Upon receipt of such a request, the Faculty Advisor shall review the matter, consult relevant parties as necessary, and determine whether sufficient grounds exist to proceed with a Presidential Review.</p>
            <p class="mt-2">The President shall not participate in any review, deliberation, or vote concerning their own Presidential Review. If a Presidential Review is initiated, the President shall be informed of the concerns and provided an opportunity to respond before any decision is made.</p>
            <p class="mt-2">Following review, the Faculty Advisor shall determine whether the concerns warrant a vote on presidential removal. Removal of the President shall require:</p>
            <ul class="list-disc ml-6 mt-2 space-y-1">
              <li>A two-thirds (2/3) majority vote of all sitting Department Directors; and</li>
              <li>Confirmation by the Faculty Advisor that the review process was conducted fairly and that sufficient grounds for removal exist.</li>
            </ul>
            <p class="mt-2">Upon removal of the President, the succession procedures outlined elsewhere in this Charter shall immediately take effect. The disciplinary authority granted to the President shall not exempt the President from review under the Presidential Accountability procedures outlined in this Charter.</p>
          </div>

          <div>
            <h4 class="text-lg font-bold">8.11 Accountability Records</h4>
            <p>The club may maintain internal accountability records documenting Concern Notices, Membership Reviews, leadership reviews, and disciplinary outcomes.</p>
            <p class="mt-2">Such records shall be treated as confidential and shall only be accessible to authorized club leadership. Members shall have the right to request information regarding any active accountability records pertaining to themselves.</p>
          </div>
        </div>
      </section>

      <section>
        <h3 id="amendments" class="text-2xl font-bold text-[#F76902] mb-4 mt-12">9. Amendments</h3>
        <p>This Charter may be amended when changes are deemed necessary to support the continued growth, effectiveness, governance, or operations of the Graphic Design Club.</p>
        <p class="mt-2">Any Club Associate may propose an amendment to this Charter by submitting the proposed amendment to the Executive Department for consideration. The Executive Department shall review and discuss all proposed amendments.</p>
        <p class="mt-2">Approval of an amendment shall require a two-thirds (2/3) majority vote of the sitting members of the Executive Department. Approved amendments shall be documented within the official Charter and communicated to the club's membership.</p>
        <p class="mt-2">The Faculty Advisor may provide guidance regarding proposed amendments but shall not possess amendment authority except where required by university policy. Unless otherwise specified, approved amendments shall take effect immediately upon adoption.</p>
